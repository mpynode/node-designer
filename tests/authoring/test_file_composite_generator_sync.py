"""The File Composite generator carries the same tier sources as the shipped
template.

``templates/MPyFile/File Composite/template.mpn`` is generated by
``_demos/build_templates.py``. When the shipped template was moved onto
``self.composite_layers`` (Compute) and lost the viewport's ``op > 0`` filter
(Init), the generator kept the old inline loop and the filter, so the next
rebuild would have quietly put both back. The shipped template is the truth.

Parsed rather than imported: build_templates initializes maya.standalone at
module scope.
"""
from __future__ import annotations

import ast
import json
import os
import unittest

from tests import _paths

_GENERATOR = os.path.join(_paths.SCRIPTS, "mpynode", "_demos",
                          "build_templates.py")
_TEMPLATE_DIR = os.path.join(_paths.ROOT, "templates", "MPyFile",
                             "File Composite")

# template.mpn data key -> generator constant
_TIERS = {
    "init_source":     "FILE_COMPOSITE_INIT",
    "expression":      "FILE_COMPOSITE_COMPUTE",
    "viewport_source": "FILE_COMPOSITE_VIEW",
    "methods_source":  "DEMO_FILE_COMPOSITE",
}


def _generator_constants(names):
    with open(_GENERATOR, encoding="utf-8") as fh:
        tree = ast.parse(fh.read())
    found = {}
    for node in tree.body:
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)
                and node.targets[0].id in names):
            found[node.targets[0].id] = ast.literal_eval(node.value)
    return found


def _shipped_data():
    with open(os.path.join(_TEMPLATE_DIR, "template.mpn"),
              encoding="utf-8") as fh:
        payload = json.load(fh)
    return payload.get("data") or payload


class TestFileCompositeGeneratorSync(unittest.TestCase):

    def setUp(self):
        names    = set(_TIERS.values())
        self.gen = _generator_constants(names)
        self.assertEqual(set(self.gen), names,
                         "build_templates is missing a File Composite constant")
        self.data = _shipped_data()

    def _check(self, key):
        const = _TIERS[key]
        self.assertEqual(self.gen[const], self.data[key],
                         "%s differs from the shipped template's %s"
                         % (const, key))

    def test_init_matches_shipped(self):
        self._check("init_source")

    def test_compute_matches_shipped(self):
        self._check("expression")

    def test_viewport_matches_shipped(self):
        self._check("viewport_source")

    def test_methods_match_shipped(self):
        self._check("methods_source")

    def test_compute_uses_the_shared_composite_method(self):
        """One SSOT for the stack: the compiled tier lowers
        ``composite_layers`` to ``nd_tex_composite_layers``."""
        self.assertIn("self.composite_layers(",
                      self.gen["FILE_COMPOSITE_COMPUTE"])

    def test_viewport_stack_has_no_opacity_filter(self):
        """Compute weights every slot; a viewport that skips ``op <= 0``
        disagrees with it for negative and NaN weights."""
        init = self.gen["FILE_COMPOSITE_INIT"]
        self.assertNotIn("op > 0.0", init)
        self.assertIn("slots = list(_layer_slots(slf))", init)


if __name__ == "__main__":
    unittest.main()
